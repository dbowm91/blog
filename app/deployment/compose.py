"""Docker Compose configuration renderers.

Generates docker-compose.yml and supporting environment files
from a DeploymentContext. Output is plain YAML text, not parsed.
"""

from __future__ import annotations

from app.deployment.model import DeploymentContext, RenderResult


def _indent(text: str, level: int) -> str:
    prefix = "  " * level
    return "\n".join(prefix + line if line.strip() else "" for line in text.splitlines())


def _compose_env_variables(ctx: DeploymentContext) -> list[tuple[str, str]]:
    vars_list: list[tuple[str, str]] = [
        ("FLASK_APP", "run:app"),
        ("FLASK_ENV", ctx.config.flask_env or "production"),
        ("SERVER_HOST", ctx.config.server.host),
        ("SERVER_PORT", str(ctx.config.server.port)),
        ("SESSION_COOKIE_SECURE", str(ctx.config.session_cookie_secure).lower()),
        ("PROXY_COUNT", str(ctx.config.proxy_count)),
        ("REDIS_URL", ctx.config.redis.url),
        ("CACHE_REDIS_URL", ctx.config.redis.cache_url or ctx.config.redis.url),
        ("CELERY_BROKER_URL", ctx.config.celery.broker_url or ctx.config.redis.url),
        ("ADMIN_USERNAME", ctx.config.admin.username),
        ("ENABLE_SCHEDULER", str(ctx.config.scheduler.enabled).lower()),
        ("ENABLE_METRICS", str(ctx.config.metrics.enabled).lower()),
    ]
    if ctx.config.email.smtp_host:
        vars_list.append(("SMTP_HOST", ctx.config.email.smtp_host))
        vars_list.append(("SMTP_PORT", str(ctx.config.email.smtp_port)))
        vars_list.append(("SMTP_USER", ctx.config.email.smtp_user))
        vars_list.append(("FROM_ADDRESS", ctx.config.email.from_address))
    if ctx.config.site.base_url:
        vars_list.append(("BASE_URL", ctx.config.site.base_url))
    return vars_list


def render_compose(ctx: DeploymentContext) -> RenderResult:
    warnings: list[str] = []
    services: list[str] = []

    web_service = f"""  web:
    build: .
    restart: unless-stopped
    labels:
      org.opencontainers.image.title: "DevLog Blog"
      org.opencontainers.image.description: "Flask blog CMS with admin dashboard, newsletter scheduling, and FTS5 search"
    expose:
      - "{ctx.bind_port}"
    ports:
      - "127.0.0.1:{ctx.bind_port}:{ctx.bind_port}"
    env_file:
      - .env
    volumes:
      - devlog_data:/data
      - devlog_config:/etc/devlog
      - devlog_logs:/var/log/devlog
    healthcheck:
      test: ["CMD", "curl", "-f", "http://localhost:{ctx.bind_port}/health"]
      interval: 30s
      timeout: 10s
      retries: 3
      start_period: 10s
    deploy:
      resources:
        limits:
          memory: 512M
        reservations:
          memory: 256M"""
    services.append(web_service)

    redis_service = """  redis:
    image: redis:7-alpine
    restart: unless-stopped
    healthcheck:
      test: ["CMD", "redis-cli", "ping"]
      interval: 10s
      timeout: 3s
      retries: 3
    deploy:
      resources:
        limits:
          memory: 128M"""

    celery_service = """  celery:
    build: .
    restart: unless-stopped
    labels:
      org.opencontainers.image.title: "DevLog Celery Worker"
      org.opencontainers.image.description: "Async task worker for newsletters, backups, and scheduled jobs"
    command: celery -A app.celery_app worker --loglevel=info --concurrency=1
    env_file:
      - .env
    environment:
      - PYTHONPATH=/home/blog
    volumes:
      - devlog_data:/data
      - devlog_config:/etc/devlog
      - devlog_logs:/var/log/devlog
    depends_on:
      redis:
        condition: service_healthy
    deploy:
      resources:
        limits:
          memory: 256M"""

    scheduler_service = """  scheduler:
    build: .
    restart: unless-stopped
    labels:
      org.opencontainers.image.title: "DevLog Scheduler"
      org.opencontainers.image.description: "APScheduler for newsletter scheduling, backups, and periodic jobs"
    command: flask scheduler-start
    env_file:
      - .env
    volumes:
      - devlog_data:/data
      - devlog_config:/etc/devlog
      - devlog_logs:/var/log/devlog
    depends_on:
      redis:
        condition: service_healthy
    deploy:
      resources:
        limits:
          memory: 256M"""

    if ctx.has_redis:
        services.append(redis_service)
    else:
        warnings.append(
            "Redis is not configured; celery and scheduler services will not be included"
        )

    if ctx.has_celery:
        services.append(celery_service)
    if ctx.has_scheduler:
        services.append(scheduler_service)

    services_yaml = "\n\n".join(services)

    content = f"""# Auto-generated by DevLog deployment system
# Do not edit manually; regenerate with: devlog deploy compose

services:
{services_yaml}

volumes:
  devlog_data:
    name: devlog_data
  devlog_config:
    name: devlog_config
  devlog_logs:
    name: devlog_logs
"""

    return RenderResult(
        content=content,
        filename="docker-compose.yml",
        target="compose",
        managed=True,
        warnings=warnings,
        permissions=0o644,
        description="Docker Compose configuration for DevLog",
    )


def render_compose_env(ctx: DeploymentContext) -> RenderResult:
    warnings: list[str] = []
    lines: list[str] = [
        "# Auto-generated by DevLog deployment system",
        "# Do not edit manually; regenerate with: devlog deploy compose",
        "#",
        "# Secrets (SECRET_KEY, ADMIN_PASSWORD, SMTP_PASSWORD, etc.) must be set",
        "# in the actual .env file or passed as environment variables at runtime.",
        "# Never commit secrets to version control.",
        "",
    ]

    env_vars = _compose_env_variables(ctx)
    for key, value in env_vars:
        if value:
            lines.append(f"{key}={value}")
        else:
            lines.append(f"# {key}=  # Set in .env")

    lines.append("")
    content = "\n".join(lines)

    return RenderResult(
        content=content,
        filename="docker-compose.env",
        target="compose",
        managed=True,
        warnings=warnings,
        permissions=0o600,
        description="Non-secret environment variables for Docker Compose",
    )
